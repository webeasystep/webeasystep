<h3>ما هو مفهوم Big-O Notation وكيف يُحسب؟</h3>
<p>يعد <strong>Big-O Notation</strong> المقياس المعياري الرياضي لوصف الحد الأعلى للتعقيد الزمني والمكاني للخوارزمية مع نمو حجم البيانات المدخلة ($n$).</p>
<ul>
    <li><strong>$O(1)$ - زمن ثابت (Constant Time):</strong> تنفيذ فوري لا يتأثر بحجم البيانات (مثل جلب عنصر من مصفوفة عبر الـ Index).</li>
    <li><strong>$O(\\log n)$ - زمن لوغاريتمي (Logarithmic Time):</strong> أداء فائق الكفاءة يقسم البيانات لنصفين في كل خطوة (مثل البحث الثنائي Binary Search).</li>
    <li><strong>$O(n)$ - زمن خطي (Linear Time):</strong> ينمو الوقت طردياً مع عدد العناصر (مثل البحث الخطي في قائمة غير مرتبة).</li>
    <li><strong>$O(n \\log n)$ - زمن الفرز الأمثل:</strong> زمن أفضل خوارزميات الترتيب العالمية (مثل Merge Sort و Quick Sort).</li>
    <li><strong>$O(n^2)$ - زمن تربيعي:</strong> بطيء جداً وغير مناسب للبيانات الضخمة (مثل الحلقات التكرارية المتداخلة في Bubble Sort).</li>
</ul>

<h3>أشهر استراتيجيات تصميم الخوارزميات في منهج SEU</h3>
<ol>
    <li><strong>استراتيجية فرّق تَسُد (Divide and Conquer):</strong> تقسيم المشكلة الكبيرة إلى مشاكل أصغر وحلها ثم دمج الحلول (Merge Sort & Binary Search).</li>
    <li><strong>الخوارزميات الجشعة (Greedy Algorithms):</strong> اختيار الخيار الأفضل محلياً في كل خطوة للوصول للحل الأمثل (مثل خوارزميات Kruskal و Prim و Dijkstra).</li>
    <li><strong>البرمجة الديناميكية (Dynamic Programming):</strong> تخزين حلول المشكلات الفرعية في مصفوفة وتجنب إعادة حسابها (Memoization) لحل مشكلات معقدة مثل مسألة حقيبة الظهر (Knapsack Problem).</li>
</ol>

