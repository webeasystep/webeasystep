<h3>الأركان الأربعة الكبرى للبرمجة كائنية التوجه (Four Pillars of OOP)</h3>
<ul>
    <li><strong>1. التغليف والكبسلة (Encapsulation):</strong>
        <p>إخفاء البيانات الحساسة داخل الفئة (Class) بجعل المتغيرات <code>private</code>، وتوفير دوال التحكم والوصول العامة (Getters & Setters) لحماية البيانات من التعديل العشوائي.</p>
    </li>
    <li><strong>2. الوراثة (Inheritance):</strong>
        <p>إمكانية اشتقاق فئات فرعية (Subclasses) من فئة رئيسية (Superclass) باستخدام الكلمة المفتاحية <code>extends</code> لإعادة استخدام الكود ومنع التكرار.</p>
    </li>
    <li><strong>3. تعدد الأشكال (Polymorphism):</strong>
        <p>القدرة على اتخاذ الدالة الواحدة لأشكال متعددة؛ سواء عبر التحميل الزائد للدوال (Method Overloading) في نفس الفئة، أو تجاوز الدوال (Method Overriding) في الفئات المشتقة.</p>
    </li>
    <li><strong>4. التجريد (Abstraction):</strong>
        <p>التركيز على "ماذا تفعل الدالة" بدلاً من "كيف تفعله"؛ وذلك باستخدام الفئات المجردة (Abstract Classes) والواجهات البرمجية (Interfaces) باستخدام <code>implements</code>.</p>
    </li>
</ul>

