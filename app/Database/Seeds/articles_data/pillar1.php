    <li><strong>معادلات الخطوط المستقيمة (Parallel & Perpendicular Lines):</strong> استنتاج ميل المستقيم الموازي ($m_1 = m_2$) أو المتعامد ($m_1 \\cdot m_2 = -1$) وكتابة المعادلة بصيغة الميل والمقطع ($y = mx + b$).</li>
    <li><strong>قوانين اللوغاريتمات والأسس:</strong> تفكيك وضم المقادير اللوغاريتمية باستخدام قوانين الضرب والقسمة وقوى الأسس، وقاعدة تغيير الأساس (Change of Base).</li>
    <li><strong>حل متباينات القيمة المطلقة:</strong> التمييز الدقيق بين حالة الأصغر من ($|x| < a$) التي تمثل فترة محصورة (AND)، وحالة الأكبر من ($|x| > a$) التي تمثل اتحاد فترتين (OR).</li>
</ul>

